import numpy as np

a = np.array([[10, 20],
              [30, 40]])

b = np.array([[2, 4],
              [5, 10]])

print("Addition:")
print(a + b)

print("Subtraction:")
print(a - b)

print("Multiplication:")
print(a * b)

print("Division:")
print(a / b)

print("Transpose:")
print(a.T)

print("Exponential:")
print(np.exp(a))